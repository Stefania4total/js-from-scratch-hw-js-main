/*
Задание: Реализация интерактивного отсчёта запуска ракеты

Цель задания: Написать код для обработки событий нажатия на кнопки "Старт" и "Отмена",
реализуя обратный отсчёт с помощью JavaScript.

Задача:

1. Добавить обработчик событий для кнопки "Старт":

- При нажатии на кнопку "Старт" должен начаться обратный отсчёт с 3 до 1. 
Значение счётчика должно отображаться в элементе countdownDisplay. Цифра 3 должна отобразиться немедленно.
- Каждую секунду значение счётчика должно уменьшаться на 1.
- Когда счётчик достигнет 0, вместо 0 должен отображаться эмодзи ракеты "🚀"
и таймер должен быть остановлен. Пользователь видит: 3 -> 2 -> 1 -> 🚀


2. Добавить обработчик событий для кнопки "Отмена":

- При нажатии на кнопку "Отмена" таймер должен быть остановлен
- В элементе отображения счётчика (countdownDisplay) должно появиться сообщение "Отменено".
- Отмена таймера возможна только во время его работы
- После отмены таймера возможен повторный запуск ракеты

Обратите внимание на корректность работы таймера: повторное нажатие на "Старт" 
не должно приводить к нескольким одновременно работающим таймерам.

Подсказки:
- 🧙‍♂️ Для выполнения этого задания нужно познакомиться с браузерными функциями 
ВsetInterval (https://doka.guide/js/setinterval/) и clearInterval(https://doka.guide/js/clearinterval/). Они очень похоже на setTimeout и clearTimeout.
 */

const startButton = document.getElementById('start')
const cancelButton = document.getElementById('cancel')
const countdownDisplay = document.getElementById('countdown')

let isTimerStarted = false  // Флаг: показывает, запущен ли сейчас таймер
let timerId  // Здесь будем хранить ID нашего таймера

startButton.addEventListener('click', () => {
  let counter = 3
  
  // 1. Проверяем: не запущен ли уже таймер?
  // Если isTimerStarted = true, значит таймер уже работает, и мы не должны запускать ещё один
  if (isTimerStarted) {
    return  // Просто выходим из функции, ничего не делаем
  }
  
  // 2. Ставим флаг, что таймер теперь запущен
  isTimerStarted = true
  
  // 3. Сразу показываем первую цифру (3)
  countdownDisplay.textContent = counter
  
  // 4. Запускаем таймер, который будет срабатывать каждую секунду (1000 миллисекунд)
  timerId = setInterval(() => {
    // 5. Уменьшаем счётчик на 1
    counter = counter - 1
    
    // 6. Проверяем, что показывать:
    if (counter > 0) {
      // Если counter больше 0 (то есть 1 или 2), показываем цифру
      countdownDisplay.textContent = counter
    } else {
      // Если counter стал 0 или меньше, значит время вышло
      
      // 7. Показываем ракету вместо цифры
      countdownDisplay.textContent = '🚀'
      
      // 8. Останавливаем таймер (больше он не нужен)
      clearInterval(timerId)
      
      // 9. Сбрасываем флаг - таймер больше не работает
      isTimerStarted = false
    }
  }, 1000)  // Интервал: 1000 миллисекунд = 1 секунда
})

cancelButton.addEventListener('click', () => {
  // 1. Проверяем: запущен ли таймер сейчас?
  // Если isTimerStarted = false, значит таймер не работает, и отменять нечего
  if (!isTimerStarted) {
    return  // Выходим из функции
  }
  
  // 2. Останавливаем таймер
  clearInterval(timerId)
  
  // 3. Показываем сообщение об отмене
  countdownDisplay.textContent = 'Отменено'
  
  // 4. Сбрасываем флаг - таймер больше не работает
  isTimerStarted = false
})